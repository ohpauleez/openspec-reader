import assert from 'node:assert/strict';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { launchExtension } from './firefox';
import { readFile } from 'node:fs/promises';

const session = await launchExtension({ nativeJar: resolve(process.env.ALLOY_JAR ?? '../.opencode/opt/alloy_v6.2.0.jar') });
const target = '/alloy.html';
const evaluate = (script: string) => session.debug.evaluate(target, script);
const wait = (script: string) => session.debug.wait(target, script);
const click = (label: string) => evaluate(`Array.from(document.querySelectorAll('button')).find(b => b.textContent === ${JSON.stringify(label)}).click(); return true;`);
try {
  const reader = await session.context.newPage();
  await reader.goto(pathToFileURL(resolve('tests/fixtures/temporal.als')).href);
  await reader.waitForSelector('html[data-osr-reader="ready"]');
  await reader.getByRole('button', { name: 'Explore model', exact: true }).click();
  await wait(`return document.querySelector('.workspace-header h1')?.textContent;`);
  await session.debug.clickTrusted(target, 'Connect local Alloy');
  try { await wait(`return document.querySelector('.analysis-panel .status')?.textContent.includes('Local bridge connected');`); }
  catch (error) { console.error('Bridge status:', await evaluate(`return document.querySelector('.analysis-panel .status').textContent;`)); throw error; }
  await click('Load commands');
  await wait(`return document.querySelector('select[aria-label="Alloy command"]').options.length === 4;`);
  await click('Run / check');
  await wait(`return document.querySelector('.timeline .current-state')?.textContent === '0';`);
  assert.ok(String(await evaluate(`return document.querySelector('.workspace-status').textContent;`)).includes('Example found'));
  await evaluate(`const color=document.querySelector('[aria-label="Color for this/Node"]');color.value='#123456';color.dispatchEvent(new Event('change'));return true;`);
  const signatureColors = () => evaluate(`return Object.fromEntries([...document.querySelectorAll('.signature-color-controls .signature-color-row')].map(row=>[row.dataset.signature,row.dataset.fill]));`);
  const initialColors = await signatureColors();
  await click('Timeline');
  await wait(`return document.querySelector('.sequence-status')?.textContent.includes('closing loop');`);
  await evaluate(`const detail=document.querySelector('[aria-label="Timeline detail"]');detail.value='changes';detail.dispatchEvent(new Event('change'));return true;`);
  await evaluate(`[...document.querySelectorAll('.sequence-explanation [data-event]')].find(b=>b.textContent.startsWith('Remove active')).click();return true;`);
  assert.ok(String(await evaluate(`return document.querySelector('.inspector .source-location')?.textContent;`)).includes('temporal.als'));
  await click('Event source');
  await wait(`return document.querySelector('.source-location')?.textContent.includes('this/Clock.active');`);
  await click('Graph');
  await click('Next state');
  await evaluate(`const input=document.querySelector('[aria-label="Alloy watch expression"]'); input.value='#Clock.active'; return true;`);
  await click('Add watch'); await click('Evaluate at selected state');
  await wait(`return document.querySelector('.watch output')?.textContent === 'State 1: 1';`);
  await evaluate(`document.querySelector('[data-atom="Clock$0"]').dispatchEvent(new KeyboardEvent('keydown', {key:'Enter',bubbles:true})); return true;`);
  await click('Relation source');
  await wait(`return document.querySelector('.source-location')?.textContent.includes('this/Clock.active');`);
  assert.ok(String(await evaluate(`return window.getSelection().toString();`)).includes('one sig Clock'));
  await evaluate(`document.querySelector('[aria-label="Alloy command"]').value='1'; return true;`);
  await click('Run / check');
  await wait(`return document.querySelector('.workspace-status').textContent.includes('Counterexample found');`);
  assert.deepEqual(await signatureColors(), initialColors);
  assert.equal(await evaluate(`return document.querySelector('[aria-label="Color for this/Node"]').value;`), '#123456');
  await evaluate(`document.querySelector('[aria-label="Alloy command"]').value='2'; return true;`);
  await click('Run / check');
  await wait(`return document.querySelector('.workspace-status').textContent.includes('No counterexample found');`);
  assert.equal(await evaluate(`return document.querySelectorAll('.visualization svg').length;`), 0);
  assert.equal(await evaluate(`return document.querySelector('.timeline .current-state');`), null);
  const markdown = await readFile('tests/fixtures/literate-spec.md', 'utf8');
  await evaluate(`const input=document.querySelector('input[aria-label="Open model / add modules"]'); const transfer=new DataTransfer(); transfer.items.add(new File([${JSON.stringify(markdown)}],'spec.md')); input.files=transfer.files; input.dispatchEvent(new Event('change',{bubbles:true})); return true;`);
  await wait(`return Array.from(document.querySelector('[aria-label="Uploaded root model"]').options).some(option=>option.value==='spec.md');`);
  await evaluate(`const root=document.querySelector('[aria-label="Uploaded root model"]'); root.value='spec.md'; root.dispatchEvent(new Event('change')); return true;`);
  assert.equal(await evaluate(`return document.querySelector('[aria-label="Root module filename"]').value;`), 'spec.md');
  await click('Load commands');
  await wait(`return document.querySelector('select[aria-label="Alloy command"]').options.length === 2;`);
  await click('Run / check');
  await wait(`return document.querySelector('.workspace-status').textContent.includes('Example found');`);
  assert.ok(String(await evaluate(`return document.querySelector('.provenance pre').textContent;`)).includes('"entryFile": "spec.md"'));
  await evaluate(`document.querySelector('[aria-label="Alloy command"]').value='1'; return true;`);
  await click('Run / check');
  await wait(`return document.querySelector('.workspace-status').textContent.includes('Counterexample found');`);
  console.log('Firefox live Alloy checks passed: optional permission, installed native host, project JAR, command load/run/check, temporal playback, watches, and UNSAT result separation.');
} finally { await session.close(); }
